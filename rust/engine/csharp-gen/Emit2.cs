    void EmitJsonGlue()
    {
        var sb = new StringBuilder();
        sb.AppendLine("//! The System.Text.Json members of every event and of `GameSettings`, in the order C# writes them.");
        sb.AppendLine("//!");
        sb.AppendLine("//! GENERATED by engine/csharp-gen from `JsonSerializerOptions.GetTypeInfo` (the same options as");
        sb.AppendLine("//! `Utilities.Serialize`). Regenerate rather than edit. The machinery is in json.rs.");
        sb.AppendLine();
        sb.AppendLine("#![allow(unused_variables, unused_imports, clippy::all)]");
        sb.AppendLine();
        sb.AppendLine("use crate::json::{FromJson, JsonError, JsonObject, JsonValue, JsonWriter};");
        sb.AppendLine("use crate::prelude::*;");
        sb.AppendLine();

        var types = ConcreteEvents.Concat([Model.Types["GameSettings"]]).ToList();
        foreach (var t in types)
        {
            var ti = StjOptions.GetTypeInfo(t.Runtime!);
            var members = new List<(string json, string access)>();
            foreach (var p in ti.Properties)
            {
                if (p.Get == null && p.Set == null) continue; // [JsonIgnore]
                var mi = p.AttributeProvider as MemberInfo;
                var csName = mi!.Name;
                // A serialized property that aliases another member (`get => X; set => X = value;`).
                if (mi is PropertyInfo pi && t.Sym.GetMembers(pi.Name).FirstOrDefault() is IPropertySymbol ps &&
                    ps.DeclaringSyntaxReferences.FirstOrDefault()?.GetSyntax() is Microsoft.CodeAnalysis.CSharp.Syntax.PropertyDeclarationSyntax pds &&
                    pds.AccessorList?.Accessors.FirstOrDefault(a => a.Keyword.Text == "get")?.ExpressionBody?.Expression is Microsoft.CodeAnalysis.CSharp.Syntax.IdentifierNameSyntax alias)
                    csName = alias.Identifier.Text;
                string? access = null;
                // Find the field: own fields, then base chain.
                foreach (var owner in new[] { t }.Concat(t.Kind == TKind.Event ? EventBaseChain(t) : []))
                {
                    var f = FieldsOf(owner).FirstOrDefault(x => x.CsName == csName);
                    if (f == null) continue;
                    access = owner.Name == "GameEvent" ? "base." + f.Rust : f.Rust;
                    JsonMemberTypes.Add(f.RustType);
                    break;
                }
                if (access == null)
                {
                    Model.Warnings.Add($"json: {t.Name}.{csName} is not a field");
                    continue;
                }
                members.Add((p.Name, access));
            }

            sb.AppendLine($"impl JsonObject for {t.Name} {{");
            sb.AppendLine("    fn write_members(&self, w: &mut JsonWriter) {");
            foreach (var (j, a) in members) sb.AppendLine($"        w.member({Lit(j)}, &self.{a});");
            sb.AppendLine("    }");
            sb.AppendLine();
            sb.AppendLine("    fn read_member(&mut self, key: &str, value: &JsonValue) -> Result<bool, JsonError> {");
            sb.AppendLine("        match key {");
            foreach (var (j, a) in members) sb.AppendLine($"            {Lit(j)} => self.{a} = FromJson::from_json(value)?,");
            sb.AppendLine("            _ => return Ok(false),");
            sb.AppendLine("        }");
            sb.AppendLine("        Ok(true)");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            sb.AppendLine();
        }

        sb.AppendLine("impl GameEvent {");
        sb.AppendLine("    /// Writes the members (without `$type`).");
        sb.AppendLine("    pub(crate) fn write_json_members(&self, w: &mut JsonWriter) {");
        sb.AppendLine("        crate::events::dispatch!(self, e => JsonObject::write_members(&**e, w))");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    /// Builds an event of type `t` from a JSON object (members after `$type`).");
        sb.AppendLine("    pub(crate) fn read_json(t: GameEventType, members: &[(String, JsonValue)]) -> Result<GameEvent, JsonError> {");
        sb.AppendLine("        Ok(match t {");
        foreach (var e in ConcreteEvents)
            sb.AppendLine($"            GameEventType::{e.Name} => GameEvent::{e.Name}(Rc::new(crate::json::read_object::<{e.Name}>(members)?)),");
        sb.AppendLine("        })");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        Write("json_members.rs", sb.ToString());
    }

