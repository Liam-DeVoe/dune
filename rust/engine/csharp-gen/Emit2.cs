    public void Report(string outDir)
    {
        Directory.CreateDirectory(outDir);
        var sb = new StringBuilder();
        sb.AppendLine("| C# file | Lines | Rust module | todo!s |");
        sb.AppendLine("|---|---:|---|---:|");
        foreach (var (path, rel) in _modules)
        {
            var lines = File.ReadAllLines(Path.Combine(Model.SharedDir, rel)).Length;
            sb.AppendLine($"| `{rel}` | {lines} | `src/{path}.rs` | {_todoCount.GetValueOrDefault(path)} |");
        }
        File.WriteAllText(Path.Combine(outDir, "assignments.md"), sb.ToString());
        File.WriteAllLines(Path.Combine(outDir, "warnings.txt"), Model.Warnings.Distinct());
        File.WriteAllLines(Path.Combine(outDir, "groups.txt"), GroupLog.Distinct());
        File.WriteAllLines(Path.Combine(outDir, "why.txt"), Model.FlagsOf.Where(kv => kv.Value.Game).Select(kv => $"{kv.Key.ContainingType.Name}.{kv.Key.Name}: {kv.Value.Why}").OrderBy(x => x));
        File.WriteAllLines(Path.Combine(outDir, "modules.txt"), _modules.Select(m => m.module));
        File.WriteAllLines(Path.Combine(outDir, "json_member_types.txt"), JsonMemberTypes);
        File.WriteAllLines(Path.Combine(outDir, "cells.txt"), Model.CellMembers.Select(c => c.ContainingType.Name + "." + c.Name).OrderBy(x => x));
        var summary = $"types {TypeCount}, fields {FieldCount}, methods {MethodCount}, todo! {TodoCount}, files {_modules.Count}, skipped existing {_skippedExisting.Count}";
        File.WriteAllText(Path.Combine(outDir, "summary.txt"), summary + "\n" + string.Join("\n", _skippedExisting));
        Console.WriteLine(summary);
        Console.WriteLine($"warnings: {Model.Warnings.Distinct().Count()} (see {outDir}/warnings.txt)");
    }
