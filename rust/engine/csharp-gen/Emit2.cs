    List<string> JsonDerived()
    {
        var result = new List<string>();
        foreach (var a in GameEvent.GetAttributes().Where(a => a.AttributeClass?.Name == "JsonDerivedTypeAttribute"))
            result.Add(((INamedTypeSymbol)a.ConstructorArguments[0].Value!).Name + "=" + (string)a.ConstructorArguments[1].Value!);
        return result;
    }

