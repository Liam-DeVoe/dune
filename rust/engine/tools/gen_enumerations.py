#!/usr/bin/env python3
"""Generates rust/engine/src/enumerations.rs (the enums of Shared/Enumerations.cs).

Names and values come from the C# reflection dump (tests/golden/static_data.json,
written by csharp-ref), so they are exact by construction: constants in
declaration order, ALL in Enum.GetValues order. Comments from the C# file are
not carried over.

Usage: python3 tools/gen_enumerations.py (from rust/engine)
"""
import json
import re
from pathlib import Path

ENGINE = Path(__file__).resolve().parent.parent
CS = ENGINE.parent.parent / "treachery-online" / "Shared" / "Enumerations.cs"
GOLDEN = ENGINE / "tests" / "golden" / "static_data.json"
OUT = ENGINE / "src" / "enumerations.rs"

order = re.findall(r"^public enum (\w+)", CS.read_text(encoding="utf-8-sig"), re.M)
# Enums declared in other C# files that have no hand-written port elsewhere
# (BattleFactKind lives in message.rs). Source file in the comment.
EXTRA = [
    ("AsideKind", "Model/Log/AsideLog.cs"),
    ("NexusAllianceChange", "Model/Log/BlowLog.cs"),
    ("ShipKind", "Model/Log/ShipMoveLog.cs"),
    ("BeneGesseritReactionKind", "Model/Log/ShipMoveLog.cs"),
    ("ErrorType", "Model/Result.cs"),
]
enums = {e["name"]: e for e in json.loads(GOLDEN.read_text())["enums"]}

out = []
w = out.append
w("//! Port of Enumerations.cs.")
w("//!")
w("//! The enum declarations are GENERATED by tools/gen_enumerations.py from the C#")
w("//! reflection dump; do not edit them by hand. See net_enum.rs for what a C#")
w("//! enum becomes in Rust and why. The hand-written part is at the bottom.")
w("")
w("use crate::net_enum::{net_enum, NetEnum};")
w("")
for name, source in [(n, None) for n in order] + EXTRA:
    e = enums[name]
    assert e["underlying"] == "Int32", name
    w(f"net_enum! {{")
    w(f"    /// C# `{name}`" + (" (`[Flags]`)" if e["flags"] else "") + (f", declared in {source}" if source else ""))
    w(f"    {'flags ' if e['flags'] else ''}{name} {{")
    for d in e["declared"]:
        w(f"        {d['name']} = {d['value']},")
    w("    }")
    by_value = {}
    for d in e["declared"]:
        by_value.setdefault(d["value"], d["name"])
    w("    get_values [" + ", ".join(by_value[v] for v in e["get_values"]) + "]")
    w("}")
    w("")

w("""/// `Enumerations.GetValues<T>()`: every value in `Enum.GetValues` order.
pub fn get_values<T: NetEnum>() -> impl Iterator<Item = T> {
    T::ALL.iter().copied()
}

/// `Enumerations.GetValuesExceptDefault<T>(defaultValue)`
pub fn get_values_except_default<T: NetEnum>(default_value: T) -> impl Iterator<Item = T> {
    get_values::<T>().filter(move |v| *v != default_value)
}

// EnumerationExtensions

impl Faction {
    /// `faction.ToNexus()`; panics for undefined values.
    pub fn to_nexus(self) -> Nexus {
        match self {
            Faction::None => Nexus::None,
            Faction::Fremen => Nexus::Fremen,
            Faction::Atreides => Nexus::Atreides,
            Faction::Harkonnen => Nexus::Harkonnen,
            Faction::Emperor => Nexus::Emperor,
            Faction::Guild => Nexus::Guild,
            Faction::BeneGesserit => Nexus::BeneGesserit,
            Faction::Ixian => Nexus::Ixian,
            Faction::Tleilaxu => Nexus::Tleilaxu,
            Faction::Choam => Nexus::Choam,
            Faction::Richese => Nexus::Richese,
            Faction::Ecaz => Nexus::Ecaz,
            Faction::Moritani => Nexus::Moritani,
            _ => panic!("faction out of range: {self}"),
        }
    }
}

impl Nexus {
    /// `nexus.ToFaction()`; panics for undefined values.
    pub fn to_faction(self) -> Faction {
        match self {
            Nexus::None => Faction::None,
            Nexus::Fremen => Faction::Fremen,
            Nexus::Atreides => Faction::Atreides,
            Nexus::Harkonnen => Faction::Harkonnen,
            Nexus::Emperor => Faction::Emperor,
            Nexus::Guild => Faction::Guild,
            Nexus::BeneGesserit => Faction::BeneGesserit,
            Nexus::Ixian => Faction::Ixian,
            Nexus::Tleilaxu => Faction::Tleilaxu,
            Nexus::Choam => Faction::Choam,
            Nexus::Richese => Faction::Richese,
            Nexus::Ecaz => Faction::Ecaz,
            Nexus::Moritani => Faction::Moritani,
            _ => panic!("nexus out of range: {self}"),
        }
    }
}
""")
OUT.write_text("\n".join(out))
print(f"wrote {OUT}: {len(order)} enums")
