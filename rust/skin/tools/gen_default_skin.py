#!/usr/bin/env python3
"""Writes skin/src/default_skin.rs from tests/golden/default_skin.json.

The JSON is `DefaultSkin.Default.SkinToString()`, written by the C# probe:

    cd rust/skin/csharp-ref && dotnet run -c Release -- skin-json ../tests/golden/default_skin.json
    python3 rust/skin/tools/gen_default_skin.py

Generating the tables from the C# object (rather than copying DefaultSkin.cs by hand)
keeps every label byte-identical, including the entries that Game.ExpansionLevel adds.
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "tests", "golden", "default_skin.json")
OUT = os.path.join(HERE, "..", "src", "default_skin.rs")

# C# field -> key type of its Dictionary (None for int keys).
DICT_KEYS = {
    "Concept_STR": "Concept", "MainPhase_STR": "MainPhase", "PersonName_STR": None,
    "PersonImage_URL": None, "TerritoryName_STR": None, "TerritoryBorder_SVG": None,
    "LocationCenter_Point": None, "LocationSpice_Point": None, "FactionName_STR": "Faction",
    "FactionImage_URL": "Faction", "FactionTableImage_URL": "Faction",
    "FactionFacedownImage_URL": "Faction", "FactionForceImage_URL": "Faction",
    "FactionSpecialForceImage_URL": "Faction", "FactionColor": "Faction",
    "ForceName_STR": "Faction", "SpecialForceName_STR": "Faction", "TechTokenName_STR": "TechToken",
    "TechTokenImage_URL": "TechToken", "Sound": "Milestone",
    "TreacheryCardType_STR": "TreacheryCardType", "TreacheryCardName_STR": None,
    "TreacheryCardDescription_STR": None, "TreacheryCardImage_URL": None,
    "TechTokenDescription_STR": "TechToken", "ResourceCardImage_URL": None,
    "LeaderSkillCardName_STR": "LeaderSkill", "LeaderSkillCardImage_URL": "LeaderSkill",
    "StrongholdCardName_STR": None, "StrongholdCardImage_URL": "StrongholdAdvantage",
    "HomeWorldImage_URL": "World", "HomeWorldCardImage_URL": "World", "NexusCardImage_URL": "Nexus",
    "TerrorTokenName_STR": "TerrorType", "TerrorTokenDescription_STR": "TerrorType",
    "DiscoveryTokenName_STR": "DiscoveryToken", "DiscoveryTokenDescription_STR": "DiscoveryToken",
    "DiscoveryTokenImage_URL": "DiscoveryToken", "DiscoveryTokenTypeName_STR": "DiscoveryTokenType",
    "DiscoveryTokenTypeImage_URL": "DiscoveryTokenType", "AmbassadorImage_URL": "Ambassador",
    "AmbassadorName_STR": "Ambassador", "AmbassadorDescription_STR": "Ambassador",
}
POINTS = {"MapDimensions", "PlanetCenter", "SpiceDeckLocation", "TreacheryDeckLocation", "CardSize"}
COMPUTED = {"HmsDx", "HmsRadius"}  # get-only properties: serialized, never read back


def rust_name(cs):
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", cs)
    return s.lower()


def rs_str(s):
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 0x20:
            out.append("\\u{%x}" % ord(ch))
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def num(v):
    if isinstance(v, float):
        return repr(v)
    return "%d.0" % v


def main():
    with open(SRC, encoding="utf-8") as f:
        d = json.load(f)
    lines = [
        "//! Port of DefaultSkin.cs: `DefaultSkin.Default`.",
        "//!",
        "//! GENERATED by skin/tools/gen_default_skin.py from tests/golden/default_skin.json (the C#",
        "//! `DefaultSkin.Default.SkinToString()`). Do not edit by hand; regenerate after a C# change.",
        "",
        "#![allow(clippy::all)]",
        "",
        "use treachery_engine::enumerations::*;",
        "use treachery_engine::point::PointD;",
        "",
        "use crate::skin::{Skin, SkinDictionary};",
        "",
        "/// `DefaultSkin.DEFAULT_ART_LOCATION`",
        'pub const DEFAULT_ART_LOCATION: &str = ".";',
        "",
        "/// `new()` of `DefaultSkin.Default`, built once per call. Use [`crate::default_skin()`] for the shared instance.",
        "pub fn build() -> Skin {",
        "    let mut s = Skin::default();",
    ]
    for key, value in d.items():
        if key in COMPUTED:
            continue
        field = rust_name(key)
        if key in DICT_KEYS:
            kt = DICT_KEYS[key]
            entries = []
            for k, v in value.items():
                kexpr = k if kt is None else "%s::%s" % (kt, k)
                if isinstance(v, dict):
                    vexpr = "PointD::new(%s, %s)" % (num(v["X"]), num(v["Y"]))
                else:
                    vexpr = rs_str(v) + ".to_string()"
                entries.append("        (%s, %s)," % (kexpr, vexpr))
            lines.append("    s.%s = SkinDictionary::from_vec(vec![" % field)
            lines.extend(entries)
            lines.append("    ]);")
        elif key in POINTS:
            lines.append("    s.%s = PointD::new(%s, %s);" % (field, num(value["X"]), num(value["Y"])))
        elif isinstance(value, bool):
            lines.append("    s.%s = %s;" % (field, "true" if value else "false"))
        elif isinstance(value, int):
            lines.append("    s.%s = %d;" % (field, value))
        elif isinstance(value, str):
            lines.append("    s.%s = %s.to_string();" % (field, rs_str(value)))
        else:
            raise SystemExit("unhandled member %s" % key)
    lines.append("    s")
    lines.append("}")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
