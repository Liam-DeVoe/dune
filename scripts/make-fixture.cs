// Makes screenshot fixtures: saved games in a chosen situation, described by a spec.
//
//   dotnet run scripts/make-fixture.cs -- worm-ride            # the "worm-ride" spec in fixture-specs.json -> fixtures/worm-ride.json
//   dotnet run scripts/make-fixture.cs -- describe worm-ride   # print what an existing fixture holds, without regenerating
//   dotnet run scripts/make-fixture.cs -- --all                # every spec in fixture-specs.json
//   dotnet run scripts/make-fixture.cs -- --locations          # every map location by name, with its centre
//
//   --out DIR   write the fixture to DIR instead of fixtures/
//   --seed N    start the seed search at N instead of the spec's seed
//
// A saved game is its event log, replayed on load (see Shared/Model/GameState.cs). So a fixture
// can only hold a state that legal events reach, and this tool gets there by letting six bots play
// the basic game (plus YellowSpecialForces and RedSpecialForces, ten turns) from a seed until the
// situation in the spec comes up. Bot randomness is seeded too, so the same spec and seed give the
// same file. Seeds are tried from the spec's seed upward; when the spec has no seed, the one that
// worked is written into it. Fixtures written before bot randomness was seeded cannot be
// regenerated byte for byte; regenerate one only when the scenario that uses it changes.
//
// fixture-specs.json is an object keyed by fixture name. A spec is the situation, the rules the
// case adds, and the seed:
//
//   "blue": {
//     "rules": ["BlueAdvisors"],
//     "seed": 1,
//     "situation": { "phase": "NonOrangeMove", "event": "Move", "faction": "Blue", "can": "advisors-to-fighters" }
//   }
//
// Other keys, for when a case needs them: "factions", "players", "max_turns", "max_attempts" (seeds
// to try, default 200), "place" (below), "handmade" (true: never regenerate; describe only).
//
// The situation is checked after every bot event, for each player in seat order. The first player
// that satisfies every condition becomes the actor: the seat to take after loading. Conditions:
//
//   phase                       Phase name, or a list of them
//   turn_min                    game turn at least this
//   faction, faction_not        Faction name or list; faction "any" is the default
//   event                       a GameEvent type the actor may send now, e.g. "Shipment"
//   host_event                  same, but as the host, e.g. "PerformSetup"
//   next_custom_setup           true: the actor is the next faction the host sets up
//   spice_min                   spice at least this
//   reserves_min, special_reserves_min   forces off planet at least this
//   killed_min, special_killed_min       forces in the tanks at least this
//   sectors_with_forces_min     locations on the planet with forces, outside the storm
//   special_forces_on_planet    true: has special forces somewhere on the planet
//   has_ally                    true: is allied
//   can                         named checks that need code, one or a list:
//                                 "reinforce"             can move onto a territory it already holds
//                                 "advisors-to-fighters"  Bene Gesserit can move advisors somewhere they may become fighters
//                                 "move-to-ally"          can move into a territory held by its ally
//                                 "ship-site-to-site"     may ship from one map location to another
//                                 "face-down-leader"      has a leader lying face down in the tanks
//   accompany_targets_min       Bene Gesserit may accompany a shipment to at least this many places
//   ride_sources_min            the worm can be ridden from at least this many locations
//   ride_source_with_both_types true: some ride source holds both normal and special forces
//   great_maker                 true: the worm to ride is the Great Maker
//   spice_blow_on_map           true: the latest spice blow left spice on the map
//   older_spice_piles_min       spice piles other than the latest blow, at least this
//   any_of                      list of condition objects; at least one must hold
//
// "place" sets starting forces and spice exactly, through the host's custom setup (rule
// CustomInitialForcesAndResources, added automatically). Bots then play on from there. Factions not
// listed get the usual start, with the Fremen's ten forces in Sietch Tabr. Location names are the
// ones --locations prints. This spec gives the Emperor a turn-1 shipment with Sardaukar already in
// Carthag beside the Harkonnen:
//
//   "placed-ship": {
//     "place": {
//       "Red":    { "spice": 12, "forces": { "Carthag": [0, 2], "Rim Wall West": [4, 0] } },   // [forces, special forces]
//       "Yellow": { "spice": 3,  "forces": { "Sietch Tabr": [6, 2], "False Wall West (Middle Sector)": [4, 1] } }
//     },
//     "situation": { "phase": "NonOrangeShip", "event": "Shipment", "faction": "Red" }
//   }

using System.Text.Json;
using System.Text.Json.Nodes;
using System.Text.Json.Serialization;
using Treachery.Shared;
using Treachery.Bots;
using Treachery.Shared.Model;

Message.DefaultDescriber = DefaultSkin.Default;

var scriptDir = Path.GetDirectoryName(ScriptPath())!;
var specsPath = Path.Combine(scriptDir, "fixture-specs.json");
var fixtureDir = Path.Combine(scriptDir, "fixtures");
var outDir = fixtureDir;
var describe = false;
var all = false;
int? seedOverride = null;
var names = new List<string>();
for (var i = 0; i < args.Length; i++)
{
    switch (args[i])
    {
        case "describe": describe = true; break;
        case "--all": all = true; break;
        case "--out": outDir = args[++i]; break;
        case "--seed": seedOverride = int.Parse(args[++i]); break;
        case "--locations": ListLocations(); return 0;
        default: names.Add(args[i]); break;
    }
}
if (all) names = Spec.LoadAll(specsPath).Keys.ToList();
if (names.Count == 0)
{
    Console.Error.WriteLine("usage: dotnet run scripts/make-fixture.cs -- [describe] <fixture name> [--out DIR] [--seed N] | --all | --locations");
    return 1;
}

Directory.CreateDirectory(outDir);
var failed = 0;
foreach (var name in names)
{
    if (!all) { Run(name); continue; }
    try { Run(name); }
    catch (Exception e) { failed++; Console.Error.WriteLine($"{name}: {e.Message}"); }
}
return failed == 0 ? 0 : 1;

void Run(string name)
{
    var spec = Spec.LoadAll(specsPath).GetValueOrDefault(name) ?? throw new Exception($"no spec named '{name}' in {specsPath}");
    var started = DateTime.Now;

    Game game;
    Player actor;
    if (describe || spec.Handmade)
    {
        var existing = Path.Combine(fixtureDir, name + ".json");
        game = Replay(File.ReadAllText(existing));
        actor = Find(game, spec.Situation) ?? throw new Exception($"{existing} does not match the situation of '{name}' in {specsPath}");
        Console.WriteLine(existing);
    }
    else
    {
        int seed;
        (game, actor, seed) = Generate(spec, seedOverride ?? spec.Seed ?? 1);
        var fixturePath = Path.Combine(outDir, name + ".json");
        File.WriteAllText(fixturePath, GameState.GetStateAsString(game));
        Console.WriteLine($"wrote {fixturePath} ({(DateTime.Now - started).TotalSeconds:F1}s)");
        if (spec.Seed == null && seedOverride == null)
        {
            PinSeed(specsPath, name, seed);
            Console.WriteLine($"pinned seed {seed} into {specsPath}");
        }
        else if (seed != spec.Seed)
        {
            Console.WriteLine($"note: seed {seed} reached the situation, the spec says {spec.Seed}");
        }
    }

    Describe(game, actor, spec);
    Console.WriteLine();
}

static (Game game, Player actor, int seed) Generate(Spec spec, int firstSeed)
{
    var rules = Game.RulesetDefinition[Ruleset.BasicGame].ToList();
    rules.AddRange([Rule.FillWithBots, Rule.YellowSpecialForces, Rule.RedSpecialForces]);
    rules.AddRange(spec.Rules.Select(r => Enum.Parse<Rule>(r, true)));
    if (spec.Place != null && !rules.Contains(Rule.CustomInitialForcesAndResources)) rules.Add(Rule.CustomInitialForcesAndResources);
    var factions = spec.Factions.Select(ParseFaction).ToList();

    for (var seed = firstSeed; seed < firstSeed + spec.MaxAttempts; seed++)
    {
        var game = new Game();
        new EstablishPlayers(game, Faction.None)
        {
            Players = [],
            Seed = seed,
            Time = EventTime(game),
            Settings = new GameSettings
            {
                InitialRules = rules,
                AllowedFactionsInPlay = factions,
                MaximumTurns = spec.MaxTurns,
                NumberOfPlayers = spec.Players,
            }
        }.Execute(false, true);

        // Each bot rolls its own dice; seeding them per seat keeps the same seed playing out the same way.
        var bots = game.Players.ToDictionary(p => p.Faction, p => (IBot)new ClassicBot(game, p, BotParameters.GetDefaultParameters(p.Faction), new LoggedRandom(seed * 64 + p.Seat)));

        while (game.CurrentPhase != Phase.GameEnded)
        {
            var actor = Find(game, spec.Situation);
            if (actor != null) return (game, actor, seed);
            if (game.CurrentPhase == Phase.PerformCustomSetup)
            {
                PlaceNextFaction(game, spec);
                continue;
            }
            if (NextBotEvent(game, bots) == null) throw new Exception($"seed {seed}: bots got stuck in {game.CurrentPhase}");
        }
        Console.WriteLine($"seed {seed}: not reached");
    }
    throw new Exception($"situation not reached in {spec.MaxAttempts} seeds from {firstSeed}");
}

// Fixed timestamps keep regenerated fixtures identical. The game only uses them for per-phase timers.
static DateTimeOffset EventTime(Game game) => new DateTimeOffset(2026, 1, 1, 0, 0, 0, TimeSpan.Zero).AddSeconds(game.History.Count);

static void PlaceNextFaction(Game game, Spec spec)
{
    var faction = game.NextFactionToPerformCustomSetup;
    var player = game.GetPlayer(faction);
    var placement = spec.Place?.FirstOrDefault(kvp => ParseFaction(kvp.Key) == faction).Value ?? DefaultPlacement(game, faction);
    var byName = LocationsByName(game);
    var forceLocations = new Dictionary<Location, Battalion>();
    foreach (var (locationName, amounts) in placement.Forces)
    {
        if (!byName.TryGetValue(locationName.ToLowerInvariant(), out var location))
            throw new Exception($"unknown location '{locationName}' in place.{faction}; --locations lists the names");
        if (amounts.Length != 2) throw new Exception($"place.{faction}.forces['{locationName}'] must be [forces, special forces]");
        forceLocations[location] = new Battalion(faction, amounts[0], amounts[1], location);
    }
    var evt = new PerformSetup(game, faction) { Resources = placement.Spice, ForceLocations = forceLocations, Time = EventTime(game) };
    var error = evt.Execute(true, true);
    if (error != null) throw new Exception($"place.{faction}: {error.ToString(DefaultSkin.Default)}");
}

// What the game itself would place, from Game_Setup.cs. The Fremen normally choose; here they get Sietch Tabr.
static Placement DefaultPlacement(Game game, Faction faction)
{
    var skin = DefaultSkin.Default;
    return faction switch
    {
        Faction.Green => new Placement { Spice = 10, Forces = { [skin.Describe(game.Map.Arrakeen)] = [10, 0] } },
        Faction.Black => new Placement { Spice = 10, Forces = { [skin.Describe(game.Map.Carthag)] = [10, 0] } },
        Faction.Red => new Placement { Spice = 10 },
        Faction.Orange => new Placement { Spice = 5, Forces = { [skin.Describe(game.Map.TueksSietch)] = [5, 0] } },
        Faction.Yellow => new Placement { Spice = 3, Forces = { [skin.Describe(game.Map.SietchTabr)] = [10, 0] } },
        Faction.Blue => new Placement { Spice = 5, Forces = { [skin.Describe(game.Map.PolarSink)] = [1, 0] } },
        _ => throw new Exception($"no default placement for {faction}; list it under place"),
    };
}

static Dictionary<string, Location> LocationsByName(Game game)
{
    var result = new Dictionary<string, Location>();
    foreach (var l in game.Map.Locations(false))
    {
        result[DefaultSkin.Default.Describe(l).ToLowerInvariant()] = l;
        if (l.Territory.Locations.Count == 1) result[DefaultSkin.Default.Describe(l.Territory).ToLowerInvariant()] = l;
    }
    return result;
}

static void ListLocations()
{
    var game = new Game();
    foreach (var l in game.Map.Locations(false).OrderBy(l => DefaultSkin.Default.Describe(l)))
        Console.WriteLine($"{DefaultSkin.Default.Describe(l)} {Center(game, l)}, sector {l.Sector}");
}

static Game Replay(string json)
{
    var state = GameState.Load(json);
    var game = new Game();
    foreach (var evt in state.Events)
    {
        evt.Initialize(game);
        var error = evt.Execute(false, true);
        if (error != null) throw new Exception($"replaying {evt.GetType().Name}: {error.ToString(DefaultSkin.Default)}");
    }
    return game;
}

static void PinSeed(string specsPath, string name, int seed)
{
    var specs = JsonNode.Parse(File.ReadAllText(specsPath), documentOptions: new JsonDocumentOptions { CommentHandling = JsonCommentHandling.Skip, AllowTrailingCommas = true })!.AsObject();
    var spec = specs[name]!.AsObject();
    var pinned = new JsonObject();
    foreach (var (key, value) in spec.ToList())
    {
        if (key == "situation" && !spec.ContainsKey("seed")) pinned["seed"] = seed;
        pinned[key] = key == "seed" ? seed : value?.DeepClone();
    }
    if (!pinned.ContainsKey("seed")) pinned["seed"] = seed;
    specs[name] = pinned;
    File.WriteAllText(specsPath, specs.ToJsonString(new JsonSerializerOptions { WriteIndented = true }) + "\n");
}

static Player? Find(Game game, Situation situation) => game.Players.FirstOrDefault(p => Matches(game, p, situation));

static bool Matches(Game game, Player p, Situation s)
{
    if (s.Phase != null && !Names(s.Phase).Select(n => Enum.Parse<Phase>(n, true)).Contains(game.CurrentPhase)) return false;
    if (s.TurnMin is int turn && game.CurrentTurn < turn) return false;
    if (s.Faction != null)
    {
        var allowed = Names(s.Faction);
        if (!allowed.Contains("any") && !allowed.Select(ParseFaction).Contains(p.Faction)) return false;
    }
    if (s.FactionNot != null && Names(s.FactionNot).Select(ParseFaction).Contains(p.Faction)) return false;
    if (s.Event != null && !game.GetApplicableEvents(p, false).Contains(EventType(s.Event))) return false;
    if (s.HostEvent != null && !game.GetApplicableEvents(p, true).Contains(EventType(s.HostEvent))) return false;
    if (s.NextCustomSetup == true && game.NextFactionToPerformCustomSetup != p.Faction) return false;
    if (s.SpiceMin is int spice && p.Resources < spice) return false;
    if (s.ReservesMin is int reserves && p.ForcesInReserve < reserves) return false;
    if (s.SpecialReservesMin is int specialReserves && p.SpecialForcesInReserve < specialReserves) return false;
    if (s.KilledMin is int killed && p.ForcesKilled < killed) return false;
    if (s.SpecialKilledMin is int specialKilled && p.SpecialForcesKilled < specialKilled) return false;
    if (s.SectorsWithForcesMin is int sectors && p.ForcesOnPlanet.Count(kvp => !game.IsInStorm(kvp.Key)) < sectors) return false;
    if (s.SpecialForcesOnPlanet == true && !p.ForcesOnPlanet.Any(kvp => kvp.Value.AmountOfSpecialForces > 0)) return false;
    if (s.HasAlly == true && !p.HasAlly) return false;
    if (s.Can != null && !Names(s.Can).All(c => Can(game, p, c))) return false;
    if (s.AccompanyTargetsMin is int accompany && BlueAccompanies.ValidTargets(game, p).Count() < accompany) return false;
    if (s.RideSourcesMin is int rideSources && YellowRidesMonster.ValidSources(game).Count() < rideSources) return false;
    if (s.RideSourceWithBothTypes == true && !YellowRidesMonster.ValidSources(game).Any(l => p.ForcesIn(l) > 0 && p.SpecialForcesIn(l) > 0)) return false;
    if (s.GreatMaker == true && !(YellowRidesMonster.ToRide(game)?.IsGreatMonster ?? false)) return false;
    if (s.SpiceBlowOnMap == true && !(game.LatestSpiceCardA?.Location is { } blown && game.ResourcesOnPlanet.ContainsKey(blown))) return false;
    if (s.OlderSpicePilesMin is int piles && game.ResourcesOnPlanet.Count(kvp => kvp.Key != game.LatestSpiceCardA?.Location) < piles) return false;
    if (s.AnyOf != null && !s.AnyOf.Any(alternative => Matches(game, p, alternative))) return false;
    return true;
}

static bool Can(Game game, Player p, string check) => check switch
{
    "reinforce" => ReinforceMoves(game, p).Any(),
    "advisors-to-fighters" => AdvisorMoves(game, p).Any(),
    "move-to-ally" => AllyMoves(game, p).Any(),
    "ship-site-to-site" => Shipment.MayShipCrossPlanet(game, p),
    "face-down-leader" => p.Leaders.Any(game.IsFaceDownDead),
    _ => throw new Exception($"unknown check '{check}' under can"),
};

static IEnumerable<(Location from, Location to)> Moves(Game game, Player p, string check) => check switch
{
    "reinforce" => ReinforceMoves(game, p),
    "advisors-to-fighters" => AdvisorMoves(game, p),
    "move-to-ally" => AllyMoves(game, p),
    _ => [],
};

// What the fixture holds, for whoever writes the scenario that clicks through it.
static void Describe(Game game, Player actor, Spec spec)
{
    var skin = DefaultSkin.Default;
    var seed = game.History.OfType<EstablishPlayers>().First().Seed;
    var extraRules = game.Rules.Except(Game.RulesetDefinition[Ruleset.BasicGame]).Except([Rule.FillWithBots]).ToList();
    Console.WriteLine($"seed {seed}, turn {game.CurrentTurn}, phase {game.CurrentPhase}, storm in sector {game.SectorInStorm}, rules {string.Join(", ", extraRules)}");
    Console.WriteLine($"act as {actor.Faction} in seat {actor.Seat}");
    foreach (var line in Hints(game, actor, spec.Situation)) Console.WriteLine($"  {line}");
    foreach (var (location, amount) in game.ResourcesOnPlanet.OrderByDescending(kvp => kvp.Value))
        Console.WriteLine($"  spice in {skin.Describe(location)} {Center(game, location)}: {amount}");
    foreach (var p in game.Players.OrderBy(p => p.Seat))
    {
        Console.WriteLine($"{p.Faction} ({skin.Describe(p.Faction)}), seat {p.Seat}: spice {p.Resources}, reserves {Forces(p.ForcesInReserve, p.SpecialForcesInReserve)}, killed {Forces(p.ForcesKilled, p.SpecialForcesKilled)}, ally {(p.HasAlly ? p.Ally.ToString() : "none")}, {p.TreacheryCards.Count} cards");
        foreach (var (location, battalion) in p.ForcesOnPlanet.Where(kvp => kvp.Value.TotalAmountOfForces > 0).OrderBy(kvp => skin.Describe(kvp.Key)))
            Console.WriteLine($"  {skin.Describe(location)} {Center(game, location)}: {Forces(battalion.AmountOfForces, battalion.AmountOfSpecialForces)}{(game.IsInStorm(location) ? ", in storm" : "")}");
    }
}

// The situation-specific pointers, chosen by what the actor may do now rather than by the spec's name.
static IEnumerable<string> Hints(Game game, Player actor, Situation situation)
{
    var skin = DefaultSkin.Default;
    var asPlayer = game.GetApplicableEvents(actor, false);
    var asHost = game.GetApplicableEvents(actor, true);

    if (asPlayer.Contains(typeof(Shipment)))
    {
        foreach (var to in Shipment.ValidShipmentLocations(game, actor, false, false).OrderByDescending(l => l.IsStronghold).Take(6))
            yield return $"ship to {skin.Describe(to)} {Center(game, to)}";
        if (Shipment.MayShipCrossPlanet(game, actor))
            foreach (var from in Shipment.ValidSourceLocations(game, actor).Take(4))
                yield return $"site-to-site from {skin.Describe(from)} {Center(game, from)}";
    }
    if (asPlayer.Contains(typeof(Move)))
        foreach (var check in Checks(situation).Distinct())
            foreach (var (from, to) in Moves(game, actor, check).Take(5))
                yield return $"{check}: move {skin.Describe(from)} {Center(game, from)} -> {skin.Describe(to)} {Center(game, to)}";
    if (asPlayer.Contains(typeof(Retreat)) && game.CurrentBattle != null)
    {
        yield return $"battle in {skin.Describe(game.CurrentBattle.Territory!)}, may retreat {Retreat.MaxForces(game, actor)} forces, {Retreat.MaxSpecialForces(game, actor)} special";
        foreach (var to in Retreat.ValidTargets(game, actor))
            yield return $"retreat to {skin.Describe(to)} {Center(game, to)}";
    }
    if (asPlayer.Contains(typeof(PerformYellowSetup)))
        foreach (var l in new[] { game.Map.SietchTabr }.Concat(game.Map.FalseWallSouth.Locations).Concat(game.Map.FalseWallWest.Locations))
            yield return $"place in {skin.Describe(l)} {Center(game, l)}";
    if (asHost.Contains(typeof(PerformSetup)) && game.NextFactionToPerformCustomSetup == actor.Faction)
        yield return $"the host places {actor.Faction}: {Forces(actor.ForcesInReserve, actor.SpecialForcesInReserve)} in reserve";
    if (asPlayer.Contains(typeof(YellowSentMonster)))
        foreach (var t in YellowSentMonster.ValidTargets(game).Take(8))
            yield return $"worm in {skin.Describe(t)} {Center(game, t.MiddleLocation)}";
    if (asPlayer.Contains(typeof(YellowRidesMonster)))
    {
        var toRide = YellowRidesMonster.ToRide(game);
        yield return $"{(toRide.IsGreatMonster ? "great maker" : "worm")} in {skin.Describe(toRide.Territory)}";
        foreach (var from in YellowRidesMonster.ValidSources(game))
            yield return $"ride from {skin.Describe(from)} {Center(game, from)}: {Forces(actor.ForcesIn(from), actor.SpecialForcesIn(from))}";
        foreach (var to in YellowRidesMonster.ValidTargets(game, actor).OrderByDescending(l => l.IsStronghold).Take(8))
            yield return $"ride to {skin.Describe(to)} {Center(game, to)}";
    }
    if (asPlayer.Contains(typeof(BlueAccompanies)))
        foreach (var to in BlueAccompanies.ValidTargets(game, actor))
            yield return $"accompany to {skin.Describe(to)} {Center(game, to)}";
    if (game.CurrentPhase == Phase.BlowReport && game.LatestSpiceCardA?.Location is { } blown)
        yield return $"latest blow in {skin.Describe(blown)} {Center(game, blown)}: {game.ResourcesOnPlanet.GetValueOrDefault(blown)} spice; the other piles are older";
    if (asPlayer.Contains(typeof(Bid)))
        yield return $"bidding with {actor.Resources} spice, {actor.TreacheryCards.Count} cards in hand";
    if (asPlayer.Contains(typeof(Battle)) && game.CurrentBattle != null)
        yield return $"battle in {skin.Describe(game.CurrentBattle.Territory!)} against {game.CurrentBattle.OpponentOf(actor.Faction)?.Faction}";
    if (asPlayer.Contains(typeof(Revival)))
        yield return $"may revive from {Forces(actor.ForcesKilled, actor.SpecialForcesKilled)} killed, with {actor.Resources} spice";
}

static IEnumerable<string> Checks(Situation s)
{
    foreach (var c in Names(s.Can)) yield return c;
    foreach (var alternative in s.AnyOf ?? [])
        foreach (var c in Checks(alternative)) yield return c;
}

static string Forces(int forces, int special) => (forces, special) switch
{
    (0, 0) => "none",
    (_, 0) => $"{forces} {(forces == 1 ? "force" : "forces")}",
    (0, _) => $"{special} special",
    _ => $"{forces} {(forces == 1 ? "force" : "forces")} + {special} special",
};

static string Center(Game game, Location l)
{
    try
    {
        var c = DefaultSkin.Default.GetCenter(l, game.Map);
        return $"({c.X},{c.Y})";
    }
    catch (KeyNotFoundException)
    {
        return "(off map)";
    }
}

static Faction ParseFaction(string name) => Enum.Parse<Faction>(name, true);

static Type EventType(string name) =>
    typeof(GameEvent).Assembly.GetType($"Treachery.Shared.{name}") ?? throw new Exception($"unknown event type '{name}'");

// A string or a list of strings in the spec.
static List<string> Names(JsonElement? e) => e switch
{
    null => [],
    { ValueKind: JsonValueKind.String } s => [s.GetString()!],
    { ValueKind: JsonValueKind.Array } a => a.EnumerateArray().Select(x => x.GetString()!).ToList(),
    _ => throw new Exception($"expected a string or list of strings, got {e}"),
};

static string ScriptPath([System.Runtime.CompilerServices.CallerFilePath] string path = "") => path;

// Moves of advisors into a territory where Blue may choose to arrive as fighters or advisors.
static IEnumerable<(Location from, Location to)> AdvisorMoves(Game game, Player p)
{
    foreach (var from in p.ForcesOnPlanet.Keys.Where(l => !game.IsInStorm(l) && p.SpecialForcesIn(l) > 0))
    {
        var moved = new Battalion(p.Faction, 0, p.SpecialForcesIn(from), from);
        foreach (var to in PlacementEvent.ValidTargets(game, p, from, moved))
            if (PlacementEvent.MayMoveAsAdvisors(game, p, to.Territory, true) && PlacementEvent.MayMoveAsBlueFighters(p, to.Territory))
                yield return (from, to);
    }
}

// Moves into a territory where the player's ally already has forces.
static IEnumerable<(Location from, Location to)> AllyMoves(Game game, Player p)
{
    foreach (var from in p.ForcesOnPlanet.Keys.Where(l => !game.IsInStorm(l)))
    {
        var moved = new Battalion(p.Faction, p.ForcesIn(from), p.SpecialForcesIn(from), from);
        foreach (var to in PlacementEvent.ValidTargets(game, p, from, moved))
            if (game.ContainsConflictingAlly(p, to))
                yield return (from, to);
    }
}

// Moves from one sector the player holds to another territory the player also holds.
static IEnumerable<(Location from, Location to)> ReinforceMoves(Game game, Player p)
{
    foreach (var from in p.ForcesOnPlanet.Keys.Where(l => !game.IsInStorm(l)))
    {
        var moved = new Battalion(p.Faction, p.ForcesIn(from), p.SpecialForcesIn(from), from);
        foreach (var to in PlacementEvent.ValidTargets(game, p, from, moved))
            if (to.Territory != from.Territory && p.AnyForcesIn(to) > 0 && !game.IsInStorm(to))
                yield return (from, to);
    }
}

static GameEvent? NextBotEvent(Game game, Dictionary<Faction, IBot> bots)
{
    var events = game.Players.ToDictionary(p => p, p => game.GetApplicableEvents(p, true));
    foreach (var pick in new Func<IBot, List<Type>, GameEvent?>[]
             {
                 (b, e) => b.DetermineHighestPriorityInPhaseAction(e),
                 (b, e) => b.DetermineHighPriorityInPhaseAction(e),
                 (b, e) => b.DetermineMiddlePriorityInPhaseAction(e),
                 (b, e) => b.DetermineLowPriorityInPhaseAction(e),
                 (b, e) => b.DetermineEndPhaseAction(e),
             })
    {
        foreach (var p in game.Players)
        {
            var evt = pick(bots[p.Faction], events[p]);
            if (evt == null) continue;
            evt.Time = EventTime(game);
            var error = evt.Execute(false, true);
            if (error != null) throw new Exception($"{evt.GetType().Name}: {error}");
            return evt;
        }
    }
    return null;
}

class Spec
{
    public List<string> Rules { get; set; } = [];
    public List<string> Factions { get; set; } = ["Green", "Black", "Red", "Orange", "Yellow", "Blue"];
    public int Players { get; set; } = 6;
    public int MaxTurns { get; set; } = 10;
    public int? Seed { get; set; }
    public int MaxAttempts { get; set; } = 200;
    public Situation Situation { get; set; } = new();
    public Dictionary<string, Placement>? Place { get; set; }
    public bool Handmade { get; set; }

    static readonly JsonSerializerOptions Options = new()
    {
        PropertyNamingPolicy = JsonNamingPolicy.SnakeCaseLower,
        ReadCommentHandling = JsonCommentHandling.Skip,
        AllowTrailingCommas = true,
        UnmappedMemberHandling = JsonUnmappedMemberHandling.Disallow,
    };

    public static Dictionary<string, Spec> LoadAll(string path)
    {
        try
        {
            return JsonSerializer.Deserialize<Dictionary<string, Spec>>(File.ReadAllText(path), Options) ?? throw new Exception("empty spec file");
        }
        catch (JsonException e)
        {
            throw new Exception($"{path}: {e.Message}");
        }
    }
}

